#!/usr/bin/env python3
"""
Dual-Mode Attribution Analysis for IEOR4703 Order Management

Mode 1 (Free/Unrestricted): Strategy trades every tau-bar independently.
  - Signals generated by strategy's own state/ePDF logic
  - No constraint from agent trades
  - Metrics: raw win rate, PnL vs benchmark, PnL distribution, Sharpe

Mode 2 (Restricted/Matched): Strategy forced to trade same as AIAgent.
  - Same timestamp, side, qty as agent
  - Metrics: beat agent %, execution quality, PnL vs agent

Usage:
  python dual_mode_attribution.py --mode free
  python dual_mode_attribution.py --mode matched
  python dual_mode_attribution.py --mode both
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, Optional, Tuple

import numpy as np
import pandas as pd

# ── Config ──────────────────────────────────────────────────────────────
ASSETS = [
    "EuroStoxx",
    "GBP - British Pound",
    "German Bunds - German Government Bonds",
    "Gold",
    "Heating_oil",
    "JPY - Japanese Yen",
    "Nasdaq",
]

TICK_MAP = {
    "EuroStoxx": 0.5,
    "GBP - British Pound": 0.01,
    "German Bunds - German Government Bonds": 0.01,
    "Gold": 0.1,
    "Heating_oil": 0.01,
    "JPY - Japanese Yen": 0.005,
    "Nasdaq": 0.25,
}

TICK_VALUE_MAP = {
    "EuroStoxx": 5.0,
    "GBP - British Pound": 6.25,
    "German Bunds - German Government Bonds": 10.0,
    "Gold": 10.0,
    "Heating_oil": 4.2,
    "JPY - Japanese Yen": 6.25,
    "Nasdaq": 5.0,
}

STRATEGY_DIR = Path("strategy_all")
VALIDATION_DIR = Path("validation_outputs")
OUTPUT_DIR = Path("attribution_outputs")


# ── Helpers ─────────────────────────────────────────────────────────────
def load_strategy_trades(asset: str) -> pd.DataFrame:
    """Load Mode 2 (matched) backtest trades for an asset."""
    path = STRATEGY_DIR / asset / "backtest_trades.csv"
    if not path.exists():
        raise FileNotFoundError(f"No strategy trades: {path}")
    df = pd.read_csv(path)
    df["asset"] = asset
    df["raw_tick"] = TICK_MAP[asset]
    df["tick_value"] = TICK_VALUE_MAP[asset]
    return df


def load_free_trades(asset: str) -> pd.DataFrame:
    """
    Mode 1: Build unrestricted trades from stitched_1min + features.
    Strategy trades every tau-bar using ePDF, independent of agent.
    """
    feat_path = STRATEGY_DIR / asset / "features_tau45.csv"
    stitched_path = STRATEGY_DIR / asset / "stitched_1min.csv"

    if not feat_path.exists() or not stitched_path.exists():
        raise FileNotFoundError(f"Missing data for {asset}")

    feat = pd.read_csv(feat_path, index_col=0, parse_dates=True)
    stitched = pd.read_csv(stitched_path, index_col=0, parse_dates=True)

    raw_tick = TICK_MAP[asset]
    tick_value = TICK_VALUE_MAP[asset]

    # Build tau-bar OHLC from stitched 1min
    tau = 45
    records = []

    for j in range(1, len(feat)):
        bar_start = feat.index[j]
        bar_end = feat.index[j] + pd.Timedelta(minutes=tau) if j + 1 < len(feat) else bar_start + pd.Timedelta(minutes=tau)

        # Get 1min bars in this tau window
        mask = (stitched.index >= bar_start) & (stitched.index < bar_end)
        bars_1m = stitched.loc[mask]

        if len(bars_1m) == 0:
            continue

        o = bars_1m.iloc[0]["open"]
        h = bars_1m["high"].max()
        l = bars_1m["low"].min()
        c = bars_1m.iloc[-1]["close"]

        benchmark = o  # bar open
        range_up = (h - o) / raw_tick
        range_dn = (o - l) / raw_tick

        # Simple ePDF-based signal: trade both sides
        # Use the feature data to determine state
        ell = feat["ell"].iloc[j] if "ell" in feat.columns else 0
        ell_u = feat["ell_u"].iloc[j] if "ell_u" in feat.columns else 0
        ell_d = feat["ell_d"].iloc[j] if "ell_d" in feat.columns else 0

        # Effective range in ticks
        eff_up = round(ell_u) if ell_u > 0 else 0
        eff_dn = round(ell_d) if ell_d > 0 else 0

        # Strategy: place limit at benchmark +/- effective distance
        # BUY: limit at open - eff_dn * raw_tick (cheaper)
        # SELL: limit at open + eff_up * raw_tick (higher)
        buy_limit = benchmark - eff_dn * raw_tick
        sell_limit = benchmark + eff_up * raw_tick

        # Check fill: if low <= buy_limit → buy filled at buy_limit
        buy_filled = l <= buy_limit
        sell_filled = h >= sell_limit

        qty = 1.0  # standard lot

        if buy_filled:
            pnl_buy = (benchmark - buy_limit) / raw_tick  # positive = good
            records.append({
                "datetime": bar_start,
                "asset": asset,
                "side": 1,
                "qty": qty,
                "benchmark": benchmark,
                "strategy_price": buy_limit,
                "fill_price": buy_limit,
                "filled": qty,
                "fill_rate": 1.0,
                "pnl_vs_benchmark_ticks": pnl_buy,
                "raw_tick": raw_tick,
                "tick_value": tick_value,
                "range_up_ticks": range_up,
                "range_dn_ticks": range_dn,
                "eff_up": eff_up,
                "eff_dn": eff_dn,
                "mode": "free",
            })

        if sell_filled:
            pnl_sell = (sell_limit - benchmark) / raw_tick
            records.append({
                "datetime": bar_start,
                "asset": asset,
                "side": -1,
                "qty": qty,
                "benchmark": benchmark,
                "strategy_price": sell_limit,
                "fill_price": sell_limit,
                "filled": qty,
                "fill_rate": 1.0,
                "pnl_vs_benchmark_ticks": pnl_sell,
                "raw_tick": raw_tick,
                "tick_value": tick_value,
                "range_up_ticks": range_up,
                "range_dn_ticks": range_dn,
                "eff_up": eff_up,
                "eff_dn": eff_dn,
                "mode": "free",
            })

    return pd.DataFrame(records)


def load_matched_trades() -> pd.DataFrame:
    """Load Mode 2 (restricted/matched) trades from validation output."""
    path = VALIDATION_DIR / "fair_comparison_trades.csv"
    if not path.exists():
        raise FileNotFoundError(f"No matched trades: {path}")
    df = pd.read_csv(path)
    df["raw_tick"] = df["asset"].map(TICK_MAP)
    df["tick_value"] = df["asset"].map(TICK_VALUE_MAP)
    df["pnl_ticks"] = df["pnl_vs_agent"] / df["raw_tick"]
    return df


# ── Analysis ────────────────────────────────────────────────────────────
def analyze_free_mode() -> pd.DataFrame:
    """Mode 1: Unrestricted strategy analysis."""
    print("=" * 80)
    print("MODE 1: FREE / UNRESTRICTED")
    print("Strategy trades every tau-bar, independent of agent")
    print("=" * 80)

    all_trades = []
    for asset in ASSETS:
        try:
            df = load_free_trades(asset)
            all_trades.append(df)
            print(f"  {asset}: {len(df):,} free trades")
        except Exception as e:
            print(f"  {asset}: ERROR - {e}")

    if not all_trades:
        print("No free trades generated!")
        return pd.DataFrame()

    trades = pd.concat(all_trades, ignore_index=True)

    # Per-asset analysis
    results = []
    for asset in sorted(trades["asset"].unique()):
        adf = trades[trades["asset"] == asset]
        pt = adf["pnl_vs_benchmark_ticks"]

        for side_val, side_label in [(1, "BUY"), (-1, "SELL")]:
            sdf = adf[adf["side"] == side_val]
            if len(sdf) == 0:
                continue
            spt = sdf["pnl_vs_benchmark_ticks"]

            # Regime breakdown
            for regime_name in ["high_vol", "med_vol", "low_vol"]:
                # No regime info in free mode yet, skip
                pass

            results.append({
                "asset": asset,
                "mode": "free",
                "side": side_label,
                "n_trades": len(sdf),
                "mean_pnl_ticks": spt.mean(),
                "median_pnl_ticks": spt.median(),
                "std_pnl_ticks": spt.std(),
                "pct_positive": (spt > 0).mean() * 100,
                "pct_zero": (spt == 0).mean() * 100,
                "pct_negative": (spt < 0).mean() * 100,
                "win_loss_ratio": abs(spt[spt > 0].mean() / spt[spt < 0].mean()) if (spt < 0).any() and spt[spt > 0].mean() != 0 else float('inf'),
                "mean_pnl_econ": spt.mean() * sdf["tick_value"].iloc[0],
                "total_pnl_econ": (spt * sdf["tick_value"]).sum(),
                "skewness": spt.skew(),
                "kurtosis": spt.kurtosis(),
                "p5": spt.quantile(0.05),
                "p25": spt.quantile(0.25),
                "p75": spt.quantile(0.75),
                "p95": spt.quantile(0.95),
            })

    res_df = pd.DataFrame(results)
    return res_df


def analyze_matched_mode() -> pd.DataFrame:
    """Mode 2: Restricted/matched analysis with deep attribution."""
    print("=" * 80)
    print("MODE 2: RESTRICTED / MATCHED (same trades as AIAgent)")
    print("=" * 80)

    trades = load_matched_trades()

    results = []
    for asset in sorted(trades["asset"].unique()):
        adf = trades[trades["asset"] == asset]
        pt = adf["pnl_ticks"]

        for side_val, side_label in [(1, "BUY"), (-1, "SELL")]:
            sdf = adf[adf["side"] == side_val].copy()
            if len(sdf) == 0:
                continue
            spt = sdf["pnl_ticks"]

            # Agent distance
            sdf["agent_dist_ticks"] = (sdf["agent_price"] - sdf["benchmark"]) / sdf["raw_tick"] * side_val  # signed: positive = agent in favorable direction

            near = sdf[sdf["agent_dist_ticks"].abs() <= 5]
            far = sdf[sdf["agent_dist_ticks"].abs() > 50]

            # Size
            small = sdf[sdf["order_size"] == "small"]
            large = sdf[sdf["order_size"] == "large"]

            # Regime
            regimes = {}
            for regime in sdf["regime"].unique():
                rdf = sdf[sdf["regime"] == regime]
                regimes[regime] = {
                    "n": len(rdf),
                    "mean_pnl": rdf["pnl_ticks"].mean(),
                    "beat_pct": rdf["beat_agent"].mean() * 100,
                }

            results.append({
                "asset": asset,
                "mode": "matched",
                "side": side_label,
                "n_trades": len(sdf),
                "pct_of_total": len(sdf) / len(adf) * 100,
                "mean_pnl_ticks": spt.mean(),
                "median_pnl_ticks": spt.median(),
                "std_pnl_ticks": spt.std(),
                "pct_beat_agent": sdf["beat_agent"].mean() * 100,
                "pct_positive": (spt > 0).mean() * 100,
                "pct_zero": (spt == 0).mean() * 100,
                "pct_negative": (spt < 0).mean() * 100,
                "win_loss_ratio": abs(spt[spt > 0].mean() / spt[spt < 0].mean()) if (spt < 0).any() else float('inf'),
                "mean_pnl_econ": (spt * sdf["tick_value"]).mean(),
                "total_pnl_econ": (spt * sdf["tick_value"]).sum(),
                "skewness": spt.skew(),
                "kurtosis": spt.kurtosis(),
                "p5": spt.quantile(0.05),
                "p25": spt.quantile(0.25),
                "p75": spt.quantile(0.75),
                "p95": spt.quantile(0.95),
                "top5_concentration": spt.nlargest(max(1, int(len(spt) * 0.05))).sum() / spt.sum() * 100 if spt.sum() > 0 else 0,
                "mean_agent_dist_ticks": sdf["agent_dist_ticks"].mean(),
                "corr_agent_dist_pnl": sdf["agent_dist_ticks"].corr(spt),
                # Near benchmark
                "near_bench_n": len(near),
                "near_bench_mean_pnl": near["pnl_ticks"].mean() if len(near) > 0 else np.nan,
                "near_bench_beat_pct": near["beat_agent"].mean() * 100 if len(near) > 0 else np.nan,
                # Far from benchmark
                "far_bench_n": len(far),
                "far_bench_mean_pnl": far["pnl_ticks"].mean() if len(far) > 0 else np.nan,
                "far_bench_beat_pct": far["beat_agent"].mean() * 100 if len(far) > 0 else np.nan,
                # Size
                "small_n": len(small),
                "small_mean_pnl": small["pnl_ticks"].mean() if len(small) > 0 else np.nan,
                "small_beat_pct": small["beat_agent"].mean() * 100 if len(small) > 0 else np.nan,
                "large_n": len(large),
                "large_mean_pnl": large["pnl_ticks"].mean() if len(large) > 0 else np.nan,
                "large_beat_pct": large["beat_agent"].mean() * 100 if len(large) > 0 else np.nan,
                # Regimes
                "regimes": regimes,
            })

    res_df = pd.DataFrame(results)
    return res_df


def print_attribution_report(matched_df: pd.DataFrame):
    """Print detailed attribution report for matched mode."""
    print("\n" + "=" * 90)
    print("ATTRIBUTION REPORT: Matched Mode (Restricted)")
    print("=" * 90)

    for _, row in matched_df.iterrows():
        asset = row["asset"]
        side = row["side"]
        print(f"\n{'─'*70}")
        print(f"{asset} | {side} | n={row['n_trades']:,} ({row['pct_of_total']:.0f}%)")
        print(f"{'─'*70}")
        print(f"  PnL vs Agent (ticks): mean={row['mean_pnl_ticks']:.1f}, median={row['median_pnl_ticks']:.1f}, std={row['std_pnl_ticks']:.1f}")
        print(f"  Distribution: neg={row['pct_negative']:.1f}%, zero={row['pct_zero']:.1f}%, pos={row['pct_positive']:.1f}%")
        print(f"  Beat Agent: {row['pct_beat_agent']:.1f}%  |  Win/Loss ratio: {row['win_loss_ratio']:.2f}")
        print(f"  Shape: skew={row['skewness']:.2f}, kurt={row['kurtosis']:.2f}")
        print(f"  Tails: p5={row['p5']:.1f}, p25={row['p25']:.1f}, p75={row['p75']:.1f}, p95={row['p95']:.1f}")
        print(f"  Concentration: top 5% → {row['top5_concentration']:.1f}% of total PnL")
        print(f"  Agent dist corr: {row['corr_agent_dist_pnl']:.3f}")
        print(f"  Agent near bench (|dist|≤5): n={row['near_bench_n']:,}, mean={row['near_bench_mean_pnl']:.1f}, beat={row['near_bench_beat_pct']:.1f}%")
        print(f"  Agent far from bench (|dist|>50): n={row['far_bench_n']:,}, mean={row['far_bench_mean_pnl']:.1f}, beat={row['far_bench_beat_pct']:.1f}%")
        print(f"  Small orders: n={row['small_n']:,}, mean={row['small_mean_pnl']:.1f}, beat={row['small_beat_pct']:.1f}%")
        print(f"  Large orders: n={row['large_n']:,}, mean={row['large_mean_pnl']:.1f}, beat={row['large_beat_pct']:.1f}%")

        # Regimes
        regimes = row["regimes"]
        if regimes:
            print(f"  Regimes:")
            for rname, rdata in regimes.items():
                print(f"    {rname}: n={rdata['n']:,}, mean={rdata['mean_pnl']:.1f}, beat={rdata['beat_pct']:.1f}%")


def generate_summary(matched_df: pd.DataFrame) -> pd.DataFrame:
    """Generate cross-asset comparison summary."""
    print("\n" + "=" * 90)
    print("CROSS-ASSET SUMMARY")
    print("=" * 90)

    summary_rows = []
    for asset in sorted(matched_df["asset"].unique()):
        asset_df = matched_df[matched_df["asset"] == asset]
        buy = asset_df[asset_df["side"] == "BUY"].iloc[0] if len(asset_df[asset_df["side"] == "BUY"]) > 0 else None
        sell = asset_df[asset_df["side"] == "SELL"].iloc[0] if len(asset_df[asset_df["side"] == "SELL"]) > 0 else None

        buy_pnl = buy["total_pnl_econ"] if buy is not None else 0
        sell_pnl = sell["total_pnl_econ"] if sell is not None else 0
        buy_beat = buy["pct_beat_agent"] if buy is not None else 0
        sell_beat = sell["pct_beat_agent"] if sell is not None else 0
        buy_wl = buy["win_loss_ratio"] if buy is not None else 0
        sell_wl = sell["win_loss_ratio"] if sell is not None else 0

        # Edge quality indicators
        edge_indicators = []
        if buy is not None and buy["corr_agent_dist_pnl"] > 0.7:
            edge_indicators.append("⚠️ BUY edge from agent quality")
        if sell is not None and sell["corr_agent_dist_pnl"] > 0.7:
            edge_indicators.append("⚠️ SELL edge from agent quality")
        if buy is not None and buy["pct_negative"] > 35:
            edge_indicators.append("⚠️ BUY high loss rate")
        if sell is not None and sell["pct_negative"] > 35:
            edge_indicators.append("⚠️ SELL high loss rate")
        if buy is not None and buy["top5_concentration"] > 60:
            edge_indicators.append("⚠️ BUY concentrated")
        if sell is not None and sell["top5_concentration"] > 60:
            edge_indicators.append("⚠️ SELL concentrated")

        total_pnl = buy_pnl + sell_pnl
        indicator_str = " | ".join(edge_indicators) if edge_indicators else "✅ Clean"

        print(f"\n  {asset}")
        print(f"    BUY:  pnl_econ=${buy_pnl:>14,.0f}  beat={buy_beat:.1f}%  W/L={buy_wl:.2f}")
        print(f"    SELL: pnl_econ=${sell_pnl:>14,.0f}  beat={sell_beat:.1f}%  W/L={sell_wl:.2f}")
        print(f"    TOTAL: ${total_pnl:>14,.0f}  |  {indicator_str}")

        summary_rows.append({
            "asset": asset,
            "buy_total_pnl_econ": buy_pnl,
            "sell_total_pnl_econ": sell_pnl,
            "total_pnl_econ": total_pnl,
            "buy_beat_pct": buy_beat,
            "sell_beat_pct": sell_beat,
            "buy_win_loss": buy_wl,
            "sell_win_loss": sell_wl,
            "edge_quality": indicator_str,
        })

    return pd.DataFrame(summary_rows)


# ── Main ────────────────────────────────────────────────────────────────
def main():
    parser = argparse.ArgumentParser(description="Dual-mode attribution analysis")
    parser.add_argument("--mode", choices=["free", "matched", "both"], default="both")
    parser.add_argument("--output-dir", default="attribution_outputs")
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(exist_ok=True)

    if args.mode in ("free", "both"):
        print("\n" + "▶" * 40)
        print("MODE 1: FREE / UNRESTRICTED")
        print("▶" * 40)
        free_df = analyze_free_mode()
        if not free_df.empty:
            free_df.to_csv(OUTPUT_DIR / "free_mode_attribution.csv", index=False)
            print(f"\n  Saved: {OUTPUT_DIR / 'free_mode_attribution.csv'}")

    if args.mode in ("matched", "both"):
        print("\n" + "▶" * 40)
        print("MODE 2: MATCHED / RESTRICTED")
        print("▶" * 40)
        matched_df = analyze_matched_mode()
        if not matched_df.empty:
            print_attribution_report(matched_df)
            summary_df = generate_summary(matched_df)

            # Save
            matched_df.to_csv(OUTPUT_DIR / "matched_mode_attribution.csv", index=False)
            summary_df.to_csv(OUTPUT_DIR / "attribution_summary.csv", index=False)
            print(f"\n  Saved: {OUTPUT_DIR / 'matched_mode_attribution.csv'}")
            print(f"  Saved: {OUTPUT_DIR / 'attribution_summary.csv'}")


if __name__ == "__main__":
    main()
